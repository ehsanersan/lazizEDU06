export async function exportPptx() {
  const pptx = new pptxgen();
  pptx.defineLayout({ name: "WIDE", width: 13.333, height: 7.5 });
  pptx.layout = "WIDE";
  pptx.rtlMode = true;
  pptx.author = "مجموعه لذیذ";
  pptx.title = "دستورالعمل جامع آموزش پرسنل فروش و کانتر";

  const FONT = "Vazirmatn";

  D.forEach((s, i) => {
    const slide = pptx.addSlide();
    const n = i + 1;
    slide.background = { color: BG };

    // accent bar (top-right)
    slide.addShape("rect", { x: 12.53, y: 0.55, w: 0.12, h: 0.9, fill: { color: PURPLE }, rectRadius: 0.05 });

    // slide number — yellow, top-left
    slide.addText(faPad(n), {
      x: 0.4, y: 0.35, w: 1.2, h: 0.7,
      fontFace: FONT, fontSize: 26, bold: true, color: YELLOW, align: "left",
    });

    // title
    slide.addText(s.title, {
      x: 0.9, y: 0.5, w: 11.4, h: 1.0,
      fontFace: FONT, fontSize: 30, bold: true, color: PURPLE_L,
      align: "right", rtlMode: true,
    });

    // subtitle
    if (s.sub) {
      slide.addText(s.sub, {
        x: 0.9, y: 1.5, w: 11.4, h: 0.8,
        fontFace: FONT, fontSize: 16, color: INK, align: "right", rtlMode: true,
      });
    }

    // bullets in a glass-like panel
    if (s.bullets?.length) {
      const top = s.sub ? 2.4 : 1.9;
      const panelH = Math.min(4.3, s.bullets.length * 0.62 + 0.6);
      slide.addShape("roundRect", {
        x: 0.9, y: top, w: 11.5, h: panelH,
        fill: { color: GLASS }, line: { color: "DCD6F5", width: 1 }, rectRadius: 0.12,
      });
      slide.addText(
        s.bullets.map((b) => ({
          text: b,
          options: { bullet: { code: "25C6", indent: 14 }, color: INK, breakLine: true },
        })),
        {
          x: 1.3, y: top + 0.3, w: 10.7, h: panelH - 0.6,
          fontFace: FONT, fontSize: 15, align: "right", rtlMode: true,
          color: INK, bullet: false, lineSpacingMultiple: 1.5, valign: "top",
        },
      );
    }

    // note callout
    if (s.note) {
      slide.addShape("roundRect", {
        x: 2.7, y: 6.35, w: 8, h: 0.62,
        fill: { color: "FFF6D9" }, line: { color: "F5C518", width: 1 }, rectRadius: 0.31,
      });
      slide.addText(s.note, {
        x: 2.8, y: 6.35, w: 7.8, h: 0.62,
        fontFace: FONT, fontSize: 13, bold: true, color: YELLOW,
        align: "center", rtlMode: true, valign: "middle",
      });
    }

    // audio affordance (bottom-left) + file name
    slide.addText(`🔊  ▶ پخش صدا — slide_${String(n).padStart(2, "0")}.mp3 (پخش خودکار هنگام ورود به اسلاید)`, {
      x: 0.4, y: 7.02, w: 7.5, h: 0.4,
      fontFace: FONT, fontSize: 10, color: MUTED, align: "left", rtlMode: true,
    });

    // brand footer (bottom-right)
    slide.addText("مجموعه لذیذ", {
      x: 10.9, y: 7.02, w: 2.0, h: 0.4,
      fontFace: FONT, fontSize: 10, bold: true, color: GREEN, align: "right",
    });

    // speaker notes with audio instruction
    slide.addNotes(
      `فایل صوتی: slide_${String(n).padStart(2, "0")}.mp3 — در پاورپوینت: Insert > Audio > Audio on My PC، سپس Playback > Start: Automatically و Hide During Show فعال شود.`,
    );
  });

  await pptx.writeFile({ fileName: "Lazizz-Sales-Counter-Training.pptx" });
}
